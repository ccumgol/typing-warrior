LINE = re.compile(r"^\S+ \d+:\d+\s+(.*)$")
# Characters that are hard to type are normalized to their keyboard equivalents.
NORMALIZE = {"‘": "'", "’": "'", "“": '"', "”": '"', "·": ",", "…": "...", " ": " "}


def fetch(translation: str, ref: str) -> str:
    result = subprocess.run(
        ["python3", str(SCRIPT), "quote", translation, ref],
        cwd=WIKI_DIR, capture_output=True, text=True, check=True,
    )
    verses = [m.group(1).strip() for line in result.stdout.splitlines() if (m := LINE.match(line))]
    if not verses:
        raise RuntimeError(f"No verse text for {ref}: {result.stdout or result.stderr}")
    text = " ".join(verses)
    for src, dst in NORMALIZE.items():
        text = text.replace(src, dst)
    return re.sub(r"\s+", " ", text).strip()


def main() -> None:
    translation = sys.argv[1] if len(sys.argv) > 1 else "개역한글"
    if len(REFS) != 100 or len(set(REFS)) != 100:
        raise SystemExit(f"Expected 100 unique references, got {len(set(REFS))}")
    items = [{"text": fetch(translation, ref), "source": ref} for ref in REFS]
    body = json.dumps(items, ensure_ascii=False, indent=1)
    OUT.write_text(
        f"// 성경 암송 말씀 100구절 ({translation}) - generated by tools/build-bible.py\n"
        f"export const BIBLE_TRANSLATION = {json.dumps(translation, ensure_ascii=False)};\n"
        f"export const BIBLE_VERSES = Object.freeze({body});\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(items)} verses to {OUT}")


if __name__ == "__main__":
    main()
